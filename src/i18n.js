/** 画面の文言を1つ取り出す。vars の {n} などを差し込む */
export function t(key, locale = DEFAULT_LOCALE, vars = {}) {
  const dict = DICT[locale] ?? DICT[DEFAULT_LOCALE];
  const value = dict[key] ?? DICT.en[key] ?? key;
  return String(value).replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

/** 長文（あそびかた・プライバシーポリシー）。未訳の言語は英語 */
export function prose(key, locale = DEFAULT_LOCALE) {
  const dict = PROSE[locale] ?? PROSE.en;
  return dict[key] ?? PROSE.en[key] ?? '';
}

export function proseLocale(locale) {
  return PROSE[locale] ? locale : 'en';
}

/**
 * 画面の data-i18n / data-i18n-aria / data-i18n-ph を埋める。
 * root は document でも要素でもよい（テストでは DOM を渡さず t() だけを使う）。
 */
export function applyI18n(root, locale = DEFAULT_LOCALE) {
  if (!root || typeof root.querySelectorAll !== 'function') return 0;
  let count = 0;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.getAttribute('data-i18n'), locale);
    count += 1;
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'), locale));
    count += 1;
  }
  for (const el of root.querySelectorAll('[data-i18n-ph]')) {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'), locale));
    count += 1;
  }
  return count;
}
